// Generates supabase/seed.sql from the verified facts (section 3) and the menu structure.
// Run: node scripts/build-seed.mjs
import { readFileSync, writeFileSync } from "node:fs";

const q = (s) => (s == null ? "null" : `'${String(s).replace(/'/g, "''")}'`);
const site = readFileSync(new URL("../src/lib/site.ts", import.meta.url), "utf8");
const block = site.slice(site.indexOf("export const FOUNDERS"), site.indexOf("];", site.indexOf("export const FOUNDERS")));
const founders = [...block.matchAll(/name: "(.*?)",\s*title: "(.*?)",\s*bio: "(.*?)",/gs)].map((m) => ({ name: m[1], title: m[2], bio: m[3].replace(/\\'/g, "'") }));
if (founders.length !== 4) throw new Error(`Expected 4 founders, found ${founders.length}`);
const nav = JSON.parse(readFileSync(new URL("../src/content/nav.json", import.meta.url), "utf8"));

const tiers = [
  ["free", 0, "Free", true, [
    { label: "Member account & digital ID", status: "live" },
    { label: "Free business directory listing", status: "live" },
    { label: "Ka-FLAME AI daily questions", status: "beta" },
    { label: "Resource library", status: "live" },
    { label: "Event registration", status: "live" },
  ]],
  ["starter", 1, "Starter", false, []], ["micro", 2, "Micro", false, []], ["neo", 3, "Neo", false, []],
  ["pro", 4, "Pro", false, []], ["champion", 5, "Champion", false, []],
];

const org = {
  name: "FLAME PH — Federation of Leaders Advancing MSME Ecosystem in the Philippines",
  former_name: "FAME PH — Founders' Association of MSMEs and Entrepreneurs, Inc.",
  type: "Non-stock, non-profit corporation",
  sec_no: "2024050150009-15", sec_registered_on: "2024-05-09",
  address: "Greenville Subd., Barangay San Jose, San Fernando City, Pampanga",
  email_primary: "flameph.org@gmail.com", email_partnerships: "federationofmsmes@gmail.com",
};

const settings = {
  organization: org,
  menu: nav,
  stat_thresholds: { founding_members: 50, ai_helpful_min_ratings: 20 },
  social_links: {},
  launch_date: null,
  donation_details: null,
  ai_limits: { guest: 3, free: 10, starter: 20, micro: 30, neo: 40, pro: 60, champion: 100 },
  ai_monthly_cap_usd: 0,
  legal_status: { terms: "draft", privacy: "draft", membership: "draft" },
};

let sql = `-- FLAME PH seed: verified facts (section 3) and menu structure ONLY.
-- All other content tables intentionally start empty. Generated by scripts/build-seed.mjs.

insert into public.founders (sort, name, title, bio, published) values
${founders.map((f, i) => `  (${i + 1}, ${q(f.name)}, ${q(f.title)}, ${q(f.bio)}, true)`).join(",\n")}
on conflict (name) do nothing;

insert into public.tiers (slug, sort, name, price_php, benefits, available) values
${tiers.map(([slug, sort, name, avail, benefits]) => `  (${q(slug)}, ${sort}, ${q(name)}, null, ${q(JSON.stringify(benefits))}::jsonb, ${avail})`).join(",\n")}
on conflict (slug) do nothing;

insert into public.settings (key, value, is_public) values
${Object.entries(settings).map(([k, v]) => `  (${q(k)}, ${q(JSON.stringify(v))}::jsonb, true)`).join(",\n")}
on conflict (key) do nothing;
`;
writeFileSync(new URL("../supabase/seed.sql", import.meta.url), sql);
console.log("Wrote supabase/seed.sql");
