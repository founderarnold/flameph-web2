// Bundles the calculator pages in src/calculators/*.html into a module the members-only route can serve.
// Edit the .html files, then run `node scripts/build-calculators.mjs` (it also runs before `npm run build`).
import { readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";

const dir = join(process.cwd(), "src", "calculators");
const pages = Object.fromEntries(
  readdirSync(dir)
    .filter((f) => f.endsWith(".html"))
    .sort()
    .map((f) => [f.replace(/\.html$/, ""), readFileSync(join(dir, f), "utf8")]),
);
const out = `// Generated by scripts/build-calculators.mjs from src/calculators/*.html. Do not edit by hand.\nexport const CALCULATOR_PAGES: Record<string, string> = ${JSON.stringify(pages, null, 0)};\n`;
writeFileSync(join(dir, "pages.generated.ts"), out);
console.log(`Bundled ${Object.keys(pages).length} calculator pages.`);
